// Plural ucraniano: 1 · 2–4 · 5+ (del 11 al 14 van con la forma de «muchas»).
function plural(n: number, una: string, pocas: string, muchas: string) {
  const decenas = n % 100;
  const unidades = n % 10;
  if (decenas >= 11 && decenas <= 14) return muchas;
  if (unidades === 1) return una;
  if (unidades >= 2 && unidades <= 4) return pocas;
  return muchas;
}
